def default_loader6_TPSGen(root, path_img, path_target, path_abd, path_grid2d, path_grid3d, path_grid_bm,
                           exclude_background):
    # input data paths (ori img(448,448,3), bm(448,448,2), recon(448,448))
    # img = cv2.imread(path_img, 1)[:, :, ::-1].astype(np.uint8)
    # target_img = cv2.imread(path_target, 1)[:, :, ::-1].astype(np.uint8)
    img = cv2.imread(path_img, 1).astype(np.uint8)
    target_img = cv2.imread(path_target, 1).astype(np.uint8)
    abd = cv2.imread(path_abd, cv2.IMREAD_GRAYSCALE).astype(np.uint8)
    _, mask = cv2.threshold(abd, 1, 255, cv2.THRESH_BINARY)
    grid2d = load_grid2d_mat_for_doc3d(path_grid2d)  # [h,w,(column,row)]
    grid2d[:, :, 0] = grid2d[:, :, 0] * 511 / 447
    grid2d[:, :, 1] = grid2d[:, :, 1] * 511 / 447
    grid3d = load_grid3d_mat_for_doc3d(path_grid3d)  # [depth, column, row]   # [h,w,unknown]
    grid_bm = load_grid_bm_mat_for_doc3d(path_grid_bm)
    # bm0 = cv2.resize(norm_bm[0, :, :], (512, 512))
    # bm1 = cv2.resize(norm_bm[1, :, :], (512, 512))
    # norm_bm = np.stack([bm0, bm1], axis=-1).transpose((1, 0, 2))
    # cv2.imwrite('img.jpg', img)
    # cv2.imwrite('mask.jpg', mask)
    # cv2.imwrite('target_img.jpg', target_img)
    # return cv2.resize(img, (512, 512)), cv2.resize(target_img, (512, 512)), cv2.resize(mask, (512, 512)), grid2d, grid3d
    if exclude_background:
        img = (img * mask.reshape(448, 448, 1).astype(np.float32) / 255).astype(np.uint8)
    return cv2.resize(img, (512, 512)), cv2.resize(target_img, (512, 512)), cv2.resize(mask, (
        512, 512)), grid2d, grid3d, grid_bm


